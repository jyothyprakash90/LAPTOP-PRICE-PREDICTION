@app.route("/", methods=["GET", "POST"])
def home():
    prediction = None
    processor_display = None
    ram_display = None
    storage_display = None

    if request.method == "POST":
        processor_display = float(request.form["processor"])
        ram_display = float(request.form["ram"])
        storage_display = float(request.form["storage"])

        input_data = pd.DataFrame([[processor_display, ram_display, storage_display]],
                                  columns=["Processor_Speed", "RAM_Size", "Storage_Capacity"])

        price = model.predict(input_data)[0]
        prediction = round(price, 2)

    return render_template_string(html, prediction=prediction, processor_display=processor_display, ram_display=ram_display, storage_display=storage_display)

def run_flask_app():
    app.run(debug=False, use_reloader=False, host='0.0.0.0', port=5000) # Run Flask app in a non-blocking way on port 5000

if __name__ == "__main__":
    # Start Flask app in a separate thread
    flask_thread = threading.Thread(target=run_flask_app)
    flask_thread.daemon = True
    flask_thread.start()
    print("Flask app is running in a separate thread.")

